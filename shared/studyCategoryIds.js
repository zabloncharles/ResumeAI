export function normalizeStudyCategoryId(value) {
  if (typeof value !== "string") return "general";
  const id = value.trim().toLowerCase();
  return STUDY_CATEGORY_IDS.includes(id) ? id : "general";
}

export function studyCategoryIdsPromptList() {
  return STUDY_CATEGORY_IDS.join(", ");
}
